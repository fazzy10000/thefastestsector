function decodeHtmlEntities(text: string): string {
  return text
    .replace(/&quot;/g, '"')
    .replace(/&#8217;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
}

function stripTags(html: string): string {
  return decodeHtmlEntities(html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim())
}

/** Converts legacy HTML policy content saved before structured sections existed. */
export function htmlContentToSections(html: string): PolicySection[] {
  if (!html.trim()) return []

  const blocks = html.split(/<section[^>]*>/i).filter((block) => block.trim())
  const sections: PolicySection[] = []

  for (const block of blocks) {
    const headingMatch = block.match(/<h2[^>]*>([\s\S]*?)<\/h2>/i)
    const heading = headingMatch ? stripTags(headingMatch[1]) : ''

    const paragraphs: string[] = []
    for (const match of block.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/gi)) {
      const text = stripTags(match[1])
      if (text) paragraphs.push(text)
    }

    const bullets: string[] = []
    for (const match of block.matchAll(/<li[^>]*>([\s\S]*?)<\/li>/gi)) {
      const text = stripTags(match[1])
      if (text) bullets.push(text)
    }

    if (heading || paragraphs.length || bullets.length) {
      sections.push({ heading, paragraphs, bullets })
    }
  }

  return sections
}

export function normalizePolicySections(sections: PolicySection[] | undefined): PolicySection[] {
  if (!sections?.length) return []

  return sections
    .map((section) => ({
      heading: section.heading?.trim() ?? '',
      paragraphs: (section.paragraphs ?? []).map((p) => p.trim()).filter(Boolean),
      bullets: (section.bullets ?? []).map((b) => b.trim()).filter(Boolean),
      afterBullets: (section.afterBullets ?? []).map((p) => p.trim()).filter(Boolean),
    }))
    .filter(
      (section) =>
        section.heading ||
        section.paragraphs.length ||
        section.bullets.length ||
        section.afterBullets.length,
    )
}
